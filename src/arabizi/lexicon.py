"""Function-word lists used to tell languages apart.

Function words — pronouns, prepositions, particles — are the right signal here:
they are the most frequent words in any text, they are short, and they are
almost never borrowed. Content words cross language boundaries constantly in
Moroccan speech (*"kanbghi l'ambiance"*), so they make poor evidence.

These lists are intentionally small and high-precision. A word that appears in
more than one of them is evidence of nothing, and
:func:`arabizi.detect.detect_token` reports it as ambiguous rather than
guessing.
"""

